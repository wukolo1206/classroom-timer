"""Shrink 台灣點心精靈娃娃 PNGs to 144px WebP and write points/avatars_snack.js."""
from pathlib import Path
import base64, io, json
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / '台灣點心精靈娃娃'
SIZE, MARGIN = 144, 6

def shrink(path):
    im = Image.open(path).convert('RGBA')
    im = im.crop(im.getbbox())
    inner = SIZE - 2 * MARGIN
    scale = inner / max(im.size)
    im = im.resize((max(1, round(im.width * scale)), max(1, round(im.height * scale))), Image.LANCZOS)
    canvas = Image.new('RGBA', (SIZE, SIZE), (0, 0, 0, 0))
    canvas.paste(im, ((SIZE - im.width) // 2, SIZE - MARGIN - im.height))  # feet on a shared baseline
    buf = io.BytesIO()
    canvas.save(buf, 'WEBP', quality=82, method=6)
    return 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode('ascii')

def build():
    dolls = json.loads((SRC / 'dolls_manifest.json').read_text(encoding='utf-8'))
    labels = [d['name'] for d in dolls]
    images = [shrink(SRC / d['png']) for d in dolls]
    js = ('/* Generated by tools/build_snack_avatars.py - do not edit by hand. */\n'
          'window.c408SnackAvatars = ' + json.dumps({'labels': labels, 'images': images}, ensure_ascii=False, indent=1) + ';\n')
    out = ROOT / 'points' / 'avatars_snack.js'
    out.write_text(js, encoding='utf-8', newline='\n')
    print(len(labels), 'dolls,', out.stat().st_size, 'bytes')

if __name__ == '__main__':
    build()
